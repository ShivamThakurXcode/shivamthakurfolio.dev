import { createClient } from 'redis';
const r = createClient({ url: 'redis://127.0.0.1:54331' }); await r.connect(); await r.del('s:jobs');
const sleep = (ms) => new Promise((res) => setTimeout(res, ms));
await r.xGroupCreate('s:jobs', 'workers', '$', { MKSTREAM: true });
for (const n of [1, 2, 3]) await r.xAdd('s:jobs', '*', { job: 'invoice-' + n });
console.log('=== Redis Streams: a consumer dies holding messages; XAUTOCLAIM hands them to a survivor ===');
const a = await r.xReadGroup('workers', 'worker-A', { key: 's:jobs', id: '>' }, { COUNT: 2 });
console.log('worker-A read', a[0].messages.map((m) => m.message.job).join(', '), '... and crashed without XACK');
console.log('pending list:', JSON.stringify((await r.xPending('s:jobs', 'workers')).pending), 'message(s) owned by a dead consumer');
const b = await r.xReadGroup('workers', 'worker-B', { key: 's:jobs', id: '>' }, { COUNT: 5 });
console.log('worker-B reads NEW messages only:', b[0].messages.map((m) => m.message.job).join(', '), '(the two held by A are invisible to it)');
await r.xAck('s:jobs', 'workers', b[0].messages.map((m) => m.id));
await sleep(600);
const claimed = await r.xAutoClaim('s:jobs', 'workers', 'worker-B', 500, '0-0', { COUNT: 10 });
console.log('after 500 ms idle, worker-B XAUTOCLAIMed:', claimed.messages.map((m) => m.message.job).join(', '));
const info = await r.xPendingRange('s:jobs', 'workers', '-', '+', 10);
console.log('delivery counts now:', info.map((p) => `${p.id.slice(-3)}:${p.deliveriesCounter}`).join(' '), '(count > 1 = redelivered; use it to dead-letter after N tries)');
await r.xAck('s:jobs', 'workers', claimed.messages.map((m) => m.id));
console.log('pending after ack:', (await r.xPending('s:jobs', 'workers')).pending);
await r.del('s:jobs'); await r.quit();
