import crypto from 'node:crypto';
import argon2 from 'argon2';
import bcrypt from 'bcryptjs';
import { promisify } from 'node:util';
const scrypt = promisify(crypto.scrypt);
const pw = 'correct horse battery staple';
const bench = async (label, n, fn) => { const t = performance.now(); for (let i = 0; i < n; i++) await fn(i); const per = (performance.now() - t) / n; console.log(label.padEnd(34), `${per.toFixed(3).padStart(9)} ms/hash`.padEnd(20), `≈ ${Math.round(1000 / per).toLocaleString().padStart(12)} guesses/s per core`); };
console.log('=== speed: slow is the point ===');
await bench('SHA-256 (WRONG for passwords)', 200000, (i) => crypto.createHash('sha256').update(pw + i).digest());
await bench('scrypt N=2^14 (Node default-ish)', 20, (i) => scrypt(pw + i, 'salt', 64, { N: 16384, r: 8, p: 1 }));
await bench('bcrypt cost 10 (bcryptjs, pure JS)', 5, (i) => bcrypt.hash(pw + i, 10));
await bench('bcrypt cost 12', 3, (i) => bcrypt.hash(pw + i, 12));
await bench('argon2id m=19MiB t=2 p=1 (OWASP min)', 10, (i) => argon2.hash(pw + i, { type: argon2.argon2id, memoryCost: 19456, timeCost: 2, parallelism: 1 }));
console.log('\n=== salting: same password, different hashes ===');
const h1 = await argon2.hash(pw), h2 = await argon2.hash(pw);
console.log(h1); console.log(h2);
console.log('hashes equal?', h1 === h2, '| both verify?', await argon2.verify(h1, pw), await argon2.verify(h2, pw), '| wrong pw:', await argon2.verify(h1, 'wrong'));
const s1 = crypto.createHash('sha256').update(pw).digest('hex'), s2 = crypto.createHash('sha256').update(pw).digest('hex');
console.log('unsalted SHA-256 of same password equal?', s1 === s2, '<- identical => rainbow tables / "who shares a password" leaks');
console.log('\n=== bcrypt 72-byte limit ===');
const long = 'a'.repeat(72);
const bh = await bcrypt.hash(long + 'DIFFERENT-TAIL', 4);
console.log('bcrypt verifies the 72-char prefix against a different tail:', await bcrypt.compare(long + 'another-tail', bh), '(characters after byte 72 are ignored)');
console.log('\n=== needsRehash (upgrade cost factors later) ===');
console.log('argon2.needsRehash(h1, stronger params):', argon2.needsRehash(h1, { memoryCost: 65536, timeCost: 3 }));
